export const LANG_CODES = SUPPORTED_LANGUAGES.map((l) => l.code);

export function resolveSupportedLang(raw) {
  if (!raw || typeof raw !== 'string') return 'en';
  const trimmed = raw.trim();
  if (LANG_CODES.includes(trimmed)) return trimmed;
  const lower = trimmed.toLowerCase();
  if (lower.startsWith('yue') || lower === 'zh-hk' || lower === 'zh-mo' || lower.includes('hant-hk') || lower.includes('cantonese')) {
    return 'zh-HK';
  }
  if (lower.startsWith('zh') || lower.startsWith('cmn')) {
    return 'zh-CN';
  }
  if (lower.startsWith('es')) return 'es';
  if (lower.startsWith('it')) return 'it';
  if (lower.startsWith('pt')) return 'pt';
  if (lower.startsWith('fr')) return 'fr';
  if (lower.startsWith('de')) return 'de';
  if (lower.startsWith('ar')) return 'ar';
  if (lower.startsWith('ja')) return 'ja';
  if (lower.startsWith('ko')) return 'ko';
  if (lower.startsWith('en')) return 'en';
  return 'en';
}

